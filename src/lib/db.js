// ─── db.js — all Supabase database operations ────────────────────────────────
// Handles profiles, progress, and certificates.
// Auth (login/signup/logout) lives in supabase.js + useAuth.js.

import { createClient as _createClient } from '@supabase/supabase-js';
import { supabase } from './supabase';
import { clampPosition } from '@/lib/courseRoutes';

// ── Pre-authed client factory ─────────────────────────────────────────────
// Creates a lightweight Supabase client that sends `accessToken` directly in
// the Authorization header — no getSession() calls, no Web Locks contention.
//
// Why this matters: the standard `supabase` client calls getSession() before
// every query to attach a fresh JWT. getSession() internally acquires the Web
// Locks API mutex "lock:sb-*-auth-token". If Supabase's own auto-refresh timer
// fires concurrently (which it always does on page load — it checks immediately
// whether the cached token needs refreshing) it calls lock() with steal:true,
// forcibly evicting our getSession() call and throwing:
//   "Lock was released because another request stole it"
//
// Passing the access_token we already received from onAuthStateChange bypasses
// getSession() entirely, so no lock is acquired and no contention is possible.
function makeTokenClient(accessToken) {
  const url  = process.env.NEXT_PUBLIC_SUPABASE_URL   || '';
  const anon = process.env.NEXT_PUBLIC_SUPABASE_ANON_KEY || '';
  return _createClient(url, anon, {
    auth: {
      persistSession:     false,
      autoRefreshToken:   false,
      detectSessionInUrl: false,
    },
    global: {
      headers: { Authorization: `Bearer ${accessToken}` },
    },
  });
}

// ── Cert IDs are generated by the database ────────────────────────────────
// The djb2 generator that used to live here produced only ~31 bits of entropy
// behind an 8-character facade (measured: first collision at ~55k IDs). It has
// been removed outright. public.certificates now carries a BEFORE INSERT
// trigger that assigns a 128-bit Crockford-base32 id server-side and ignores
// anything the client supplies, so a weak id cannot be minted from anywhere.

// ── Normalize DB snake_case → camelCase for the rest of the app ───────────
function normalizeCert(row) {
  return {
    certId:        row.cert_id,
    name:          row.name,
    email:         row.email,
    pct:           row.pct,
    grade:         row.grade,
    moduleScores:  row.module_scores  || [],
    totalCorrect:  row.total_correct  || 0,
    totalPossible: row.total_possible || 0,
    issuedAt:      row.issued_at,
  };
}

// ── PROFILE ───────────────────────────────────────────────────────────────

export async function getProfile(userId, accessToken) {
  const client = accessToken ? makeTokenClient(accessToken) : supabase;
  const { data, error } = await client
    .from('profiles')
    // consented_at is read-only to the client by design (migration 006 revokes
    // column UPDATE from authenticated). It is selected so the UI can tell who
    // has never been asked; only /api/consent can write it.
    .select('name, bio, avatar_url, consented_at')
    .eq('id', userId)
    .maybeSingle();
  if (error) console.error('[db] getProfile error:', error.message);
  return data || null;
}

export async function upsertProfile(userId, { name, bio = '', avatarUrl = '' }, accessToken) {
  const client = accessToken ? makeTokenClient(accessToken) : supabase;
  const { data, error } = await client
    .from('profiles')
    .upsert({ id: userId, name: name.trim(), bio, avatar_url: avatarUrl }, { onConflict: 'id' })
    .select()
    .single();
  if (error) throw new Error(error.message);
  return data;
}

// ── PROGRESS ──────────────────────────────────────────────────────────────

export async function loadProgress(userId, accessToken) {
  const client = accessToken ? makeTokenClient(accessToken) : supabase;
  const { data, error } = await client
    .from('progress')
    .select('completed, quiz_scores, last_lesson')
    .eq('user_id', userId)
    .maybeSingle();
  if (error) console.error('[db] loadProgress error:', error.message);
  if (!data) return { completed: {}, quizScores: {}, lastLesson: { m: 0, l: 0 } };
  return {
    completed:  data.completed   || {},
    quizScores: data.quiz_scores || {},
    // Clamped here, at the boundary where untrusted row data becomes app state,
    // so no consumer has to remember that last_lesson is user-writable.
    lastLesson: clampPosition(data.last_lesson),
  };
}

export async function saveProgress(userId, progress, accessToken) {
  const client = accessToken ? makeTokenClient(accessToken) : supabase;
  const { error } = await client
    .from('progress')
    .upsert({
      user_id:     userId,
      completed:   progress.completed,
      quiz_scores: progress.quizScores,
      last_lesson: progress.lastLesson,
      updated_at:  new Date().toISOString(),
    }, { onConflict: 'user_id' });
  if (error) console.error('[db] saveProgress error:', error.message);
}

// ── CERTIFICATES ──────────────────────────────────────────────────────────

/**
 * Issue via the server route. The client sends no scores, no name and no
 * identifiers — the server derives the user from the bearer token and computes
 * every field itself. See src/app/api/certificates/issue/route.js.
 *
 * Token plumbing deliberately lives in useAuth (tokenRef), not here: calling
 * getSession()/refreshSession() from this layer would reacquire the Web Locks
 * mutex that makeTokenClient() exists to avoid.
 */
export async function issueCertificateViaApi(accessToken) {
  const res = await fetch('/api/certificates/issue', {
    method: 'POST',
    headers: { Authorization: `Bearer ${accessToken}` },
  });

  let json = null;
  try { json = await res.json(); } catch { /* non-JSON error page */ }

  if (!res.ok) {
    const err = new Error(json?.error || `Certificate service returned ${res.status}.`);
    err.status = res.status;   // useAuth inspects this to decide whether to retry
    throw err;
  }

  // The route wraps its payload: { ok, issued, certificate }. Unwrap it —
  // handing the envelope to setCert would produce a cert with no certId.
  if (!json?.certificate) {
    throw new Error('Certificate service returned an unexpected response.');
  }
  return json.certificate;
}

// issueCertificateDirect() removed. It inserted the certificate row straight
// from the browser; 005b revokes INSERT from `authenticated`, so that path no
// longer exists at the database level either. Issuance goes through
// issueCertificateViaApi() -> /api/certificates/issue.

export async function getUserCert(userId, accessToken) {
  const client = accessToken ? makeTokenClient(accessToken) : supabase;
  const { data, error } = await client
    .from('certificates')
    .select('*')
    .eq('user_id', userId)
    .maybeSingle();
  if (error) console.error('[db] getUserCert error:', error.message);
  return data ? normalizeCert(data) : null;
}

// ── Public verification ───────────────────────────────────────────────────
// Maps the reduced column set returned by the verify_certificate() RPC.
// Deliberately has no `email` field: the public verify page never needed the
// certificate holder's email address, and it is not sent to the browser.
function normalizePublicCert(row) {
  return {
    certId:       row.cert_id,
    name:         row.name,
    pct:          row.pct,
    grade:        row.grade,
    moduleScores: row.module_scores || [],
    issuedAt:     row.issued_at,
  };
}

export async function getCertificateById(certId) {
  // Goes through the verify_certificate() RPC rather than reading the table.
  //
  // Why: public.certificates is no longer readable by the anon role. The old
  // implementation did `.select('*')` with anon privileges, which meant any
  // caller holding the (public) anon key could read every row of the table —
  // names and email addresses included. The RPC returns only non-PII columns,
  // and only for an exact cert_id / legacy_cert_id match, so there is no way
  // to list or page through the table.
  //
  // legacy_cert_id is matched inside the function, so verify links shared
  // before the 004 ID rotation keep resolving.
  const { data, error } = await supabase
    .rpc('verify_certificate', { p_cert_id: certId });

  if (error) {
    console.error('[db] getCertificateById error:', error.message, '| certId:', certId);
    return null;
  }

  // The function returns a set; supabase-js hands back an array.
  const row = Array.isArray(data) ? data[0] : data;
  return row ? normalizePublicCert(row) : null;
}
